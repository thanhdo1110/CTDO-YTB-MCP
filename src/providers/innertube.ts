/**
 * Fetch rich video metadata + signed caption tracks + likes + chapters + related videos
 * in ONE parallel InnerTube round-trip (IOS/ANDROID /player + WEB /next) with 0 API keys!
 */
export async function fetchInnerTubeVideoFull(
  videoInput: string,
  hl = 'en',
  gl = 'US'
): Promise<RawPlayerResult> {
  const videoId = extractVideoId(videoInput);

  return globalCache.getOrCompute(
    'it_video_full',
    { videoId, hl },
    CACHE_TTL.VIDEO,
    async () => {
      const [playerRes, nextRes] = await Promise.all([
        fetchMobilePlayer(videoId, hl, gl),
        postInnerTube('next', { videoId }, { hl, gl }).catch(() => null),
      ]);

      const vd = playerRes?.videoDetails || {};
      const micro = playerRes?.microformat?.playerMicroformatRenderer || {};
      const tracksRaw = playerRes?.captions?.playerCaptionsTracklistRenderer?.captionTracks || [];

      const captionTracks: CaptionTrackInfo[] = tracksRaw
        .filter((t: any) => Boolean(t?.baseUrl))
        .map((t: any) => ({
          baseUrl: String(t.baseUrl),
          languageCode: String(t.languageCode || 'en'),
          name: extractText(t.name) || String(t.languageCode || 'en'),
          isAutoGenerated: t.kind === 'asr',
          isTranslatable: Boolean(t.isTranslatable),
        }));

      const durationSec = parseDurationSeconds(vd.lengthSeconds);
      const views = parseHumanCount(vd.viewCount);
      const publishedAt = micro.publishDate || micro.uploadDate || undefined;
      const description = vd.shortDescription || extractText(micro.description) || undefined;

      // Extract likes, comment count, chapters, and related videos from /next
      let likes: number | undefined;
      let commentsCount: number | undefined;
      let chapters: Chapter[] = [];
      let relatedVideos: LeanVideo[] = [];

      if (nextRes) {
        const nextStr = JSON.stringify(nextRes);
        const likeMatch =
          nextStr.match(/"likeCountIfIndifferentNumber":"?(\d+)"?/) ||
          nextStr.match(/"label":"([\d,]+)\s+likes"/i);
        if (likeMatch?.[1]) {
          likes = parseHumanCount(likeMatch[1]);
        }

        const commentHeaderMatch = nextStr.match(/"contextualInfo":\{"runs":\[\{"text":"([\d.,KMB]+)"\}/i);
        if (commentHeaderMatch?.[1]) {
          commentsCount = parseHumanCount(commentHeaderMatch[1]);
        }

        chapters = parseChaptersFromNext(nextRes);
        relatedVideos = parseRelatedFromNext(nextRes);
      }

      if (chapters.length === 0 && description) {
        chapters = extractDescriptionChapters(description);
      }

      const viewsPerDay = calcViewsPerDay(views, publishedAt);
      const likeToViewPct =
        views && views > 0 && likes !== undefined ? Math.round((likes / views) * 10000) / 100 : undefined;
      const commentToViewPct =
        views && views > 0 && commentsCount !== undefined
          ? Math.round((commentsCount / views) * 10000) / 100
          : undefined;

      const isShort =
        (durationSec !== undefined && durationSec > 0 && durationSec <= 61 && Boolean(vd.isShortEligible || description?.includes('#shorts'))) ||
        (durationSec !== undefined && durationSec > 0 && durationSec <= 60);

      const video: LeanVideo = {
        id: videoId,
        url: isShort ? `https://www.youtube.com/shorts/${videoId}` : `https://www.youtube.com/watch?v=${videoId}`,
        title: vd.title || extractText(micro.title) || videoId,
        channelId: vd.channelId || micro.externalChannelId || undefined,
        channelTitle: vd.author || micro.ownerChannelName || undefined,
        channelHandle: micro.ownerProfileUrl?.split('/').pop()?.startsWith('@')
          ? micro.ownerProfileUrl.split('/').pop()
          : undefined,
        publishedAt,
        durationSec,
        duration: durationSec !== undefined ? formatTimestamp(durationSec) : undefined,
        isShort,
        isLive: Boolean(vd.isLiveContent),
        views,
        likes,
        comments: commentsCount,
        likeToViewPct,
        commentToViewPct,
        viewsPerDay,
        categoryId: micro.category || undefined,
        description,
        tags: Array.isArray(vd.keywords) ? vd.keywords : undefined,
        thumbnails: {
          default: `https://i.ytimg.com/vi/${videoId}/default.jpg`,
          hq: `https://i.ytimg.com/vi/${videoId}/hqdefault.jpg`,
          maxres: `https://i.ytimg.com/vi/${videoId}/maxresdefault.jpg`,
        },
        chapters: chapters.length > 0 ? chapters : undefined,
        captionLanguages: captionTracks.map((t) => (t.isAutoGenerated ? `${t.languageCode}(auto)` : t.languageCode)),
        source: 'innertube',
      };

      return { video, captionTracks, relatedVideos };
    }
  );
}

async function fetchMobilePlayer(videoId: string, hl: string, gl: string): Promise<any> {
  try {
    const ios = await postInnerTube('player', { videoId }, { client: IOS_CLIENT, ua: IOS_UA, hl, gl });
    if (ios?.videoDetails?.videoId) return ios;
  } catch {
    // fallback to ANDROID
  }
  return postInnerTube('player', { videoId }, { client: ANDROID_CLIENT, ua: ANDROID_UA, hl, gl });
}

/**
 * Fetch & parse transcript segments with multi-language fallback AND instant native YouTube translation!
 */
export async function fetchInnerTubeTranscript(
  videoInput: string,
  preferredLang = 'en',
  translateTo?: string
): Promise<{
  segments: TranscriptSegment[];
  language: string;
  translatedTo?: string;
  availableLanguages: string[];
}> {
  const videoId = extractVideoId(videoInput);

  return globalCache.getOrCompute(
    'it_transcript',
    { videoId, preferredLang, translateTo: translateTo || '' },
    CACHE_TTL.TRANSCRIPT,
    async () => {
      // Fresh player call if cached URL expired (signed timedtext URLs expire after ~6h)
      const player = await fetchMobilePlayer(videoId, preferredLang, 'US');
      const tracksRaw = player?.captions?.playerCaptionsTracklistRenderer?.captionTracks || [];
      const tracks: CaptionTrackInfo[] = tracksRaw
        .filter((t: any) => Boolean(t?.baseUrl))
        .map((t: any) => ({
          baseUrl: String(t.baseUrl),
          languageCode: String(t.languageCode || 'en'),
          name: extractText(t.name) || String(t.languageCode || 'en'),
          isAutoGenerated: t.kind === 'asr',
          isTranslatable: Boolean(t.isTranslatable),
        }));

      if (tracks.length === 0) {
        return { segments: [], language: preferredLang, availableLanguages: [] };
      }

      const chosen = pickBestCaptionTrack(tracks, preferredLang);
      let effectiveTranslatedTo: string | undefined;
      let segments: TranscriptSegment[] = [];

      if (translateTo && translateTo.toLowerCase() !== chosen.languageCode.toLowerCase() && chosen.isTranslatable) {
        const tUrl = `${chosen.baseUrl}&tlang=${encodeURIComponent(translateTo)}`;
        segments = await downloadAndParseCaptionUrl(`${tUrl}&fmt=json3`, IOS_UA);
        if (segments.length === 0) {
          segments = await downloadAndParseCaptionUrl(tUrl, ANDROID_UA);
        }
        if (segments.length > 0) {
          effectiveTranslatedTo = translateTo;
        }
      }

      if (segments.length === 0) {
        segments = await downloadAndParseCaptionUrl(`${chosen.baseUrl}&fmt=json3`, IOS_UA);
        if (segments.length === 0) {
          segments = await downloadAndParseCaptionUrl(chosen.baseUrl, ANDROID_UA);
        }
      }

      if (
        translateTo &&
        !effectiveTranslatedTo &&
        segments.length > 0 &&
        translateTo.toLowerCase() !== chosen.languageCode.toLowerCase()
      ) {
        segments = await translateSegmentsFallback(segments, chosen.languageCode, translateTo);
        effectiveTranslatedTo = translateTo;
      }

      return {
        segments,
        language: chosen.languageCode,
        translatedTo: effectiveTranslatedTo,
        availableLanguages: tracks.map((t) => t.languageCode),
      };
    }
  );
}

function pickBestCaptionTrack(tracks: CaptionTrackInfo[], preferredLang: string): CaptionTrackInfo {
  const pref = preferredLang.toLowerCase();
  const fallbackOrder = [pref, 'en', 'vi', 'es', 'ja', 'ko', 'zh', 'fr', 'de'];

  for (const lang of fallbackOrder) {
    // Prefer manual human captions over ASR
    const manualExact = tracks.find((t) => t.languageCode.toLowerCase() === lang && !t.isAutoGenerated);
    if (manualExact) return manualExact;
    const anyExact = tracks.find((t) => t.languageCode.toLowerCase() === lang);
    if (anyExact) return anyExact;
    const prefixMatch = tracks.find((t) => t.languageCode.toLowerCase().startsWith(`${lang}-`));
    if (prefixMatch) return prefixMatch;
  }

  return tracks.find((t) => !t.isAutoGenerated) || tracks[0];
}

async function downloadAndParseCaptionUrl(url: string, ua: string): Promise<TranscriptSegment[]> {
  try {
    const res = await fetch(url, {
      headers: { 'User-Agent': ua },
      signal: AbortSignal.timeout(10_000),
    });
    if (!res.ok) return [];
    const raw = await res.text();
    if (!raw || raw.length < 10) return [];

    const trimmed = raw.trim();
    if (trimmed.startsWith('{')) {
      return parseJson3Captions(trimmed);
    }
    return parseXmlCaptions(trimmed);
  } catch {
    return [];
  }
}

function parseJson3Captions(rawJson: string): TranscriptSegment[] {
  try {
    const data = JSON.parse(rawJson);
    const events = Array.isArray(data?.events) ? data.events : [];
    const out: TranscriptSegment[] = [];

    for (const ev of events) {
      if (!Array.isArray(ev?.segs)) continue;
      const text = ev.segs
        .map((s: any) => String(s?.utf8 || ''))
        .join('')
        .replace(/\s+/g, ' ')
        .trim();
      if (!text) continue;
      const startSec = Math.round((Number(ev.tStartMs || 0) / 1000) * 100) / 100;
      const durationSec = Math.round((Number(ev.dDurationMs || 2000) / 1000) * 100) / 100;
      out.push({
        startSec,
        durationSec,
        timestamp: formatTimestamp(startSec),
        text: decodeHtmlEntities(text),
      });
    }
    return out;
  } catch {
    return [];
  }
}

function parseXmlCaptions(xml: string): TranscriptSegment[] {
  const out: TranscriptSegment[] = [];
  // Format 3: <p t="1360" d="1680">...</p> OR Format 1: <text start="1.36" dur="1.68">...</text>
  const pRegex = /<(p|text)\b([^>]*)>([\s\S]*?)<\/\1>/gi;
  let match: RegExpExecArray | null;

  while ((match = pRegex.exec(xml)) !== null) {
    const tag = match[1].toLowerCase();
    const attrs = match[2];
    const body = match[3].replace(/<[^>]+>/g, '');
    const text = decodeHtmlEntities(body);
    if (!text) continue;

    let startSec = 0;
    let durationSec = 2;
    if (tag === 'p') {
      const t = attrs.match(/\bt="(\d+)"/)?.[1];
      const d = attrs.match(/\bd="(\d+)"/)?.[1];
      startSec = t ? Number(t) / 1000 : 0;
      durationSec = d ? Number(d) / 1000 : 2;
    } else {
      const s = attrs.match(/\bstart="([\d.]+)"/)?.[1];
      const d = attrs.match(/\bdur="([\d.]+)"/)?.[1];
      startSec = s ? Number(s) : 0;
      durationSec = d ? Number(d) : 2;
    }

    out.push({
      startSec: Math.round(startSec * 100) / 100,
      durationSec: Math.round(durationSec * 100) / 100,
      timestamp: formatTimestamp(startSec),
      text,
    });
  }
  return out;
}

async function translateSegmentsFallback(
  segments: TranscriptSegment[],
  sourceLang: string,
  targetLang: string
): Promise<TranscriptSegment[]> {
  try {
    // Batch lines in groups of 40 separated by newline to minimize HTTP requests
    const batchSize = 40;
    const translated: TranscriptSegment[] = [];
    for (let i = 0; i < segments.length; i += batchSize) {
      const slice = segments.slice(i, i + batchSize);
      const joined = slice.map((s) => s.text.replace(/\n/g, ' ')).join('\n');
      const url = `https://translate.googleapis.com/translate_a/single?client=gtx&sl=${encodeURIComponent(
        sourceLang
      )}&tl=${encodeURIComponent(targetLang)}&dt=t&q=${encodeURIComponent(joined)}`;
      const res = await fetch(url, { signal: AbortSignal.timeout(8_000) });
      if (!res.ok) return segments;
      const json = (await res.json()) as any[];
      const fullTranslated = (json?.[0] || []).map((part: any) => String(part?.[0] || '')).join('');
      const lines = fullTranslated.split('\n');
      slice.forEach((seg, idx) => {
        translated.push({ ...seg, text: (lines[idx] || seg.text).trim() });
      });
    }
    return translated;
  } catch {
    return segments;
  }
}

/**
 * Zero-API-Key InnerTube Search (supports videos, Shorts, channels, playlists + sorting).
 */
export async function searchInnerTube(options: {
  query: string;
  type?: 'video' | 'short' | 'channel' | 'playlist';
  sort?: 'relevance' | 'date' | 'views' | 'rating';
  maxResults?: number;
  hl?: string;
  gl?: string;
}): Promise<{ videos: LeanVideo[]; channels: LeanChannel[]; playlists: LeanPlaylist[] }> {
  const { query, type = 'video', sort = 'relevance', maxResults = 15, hl = 'en', gl = 'US' } = options;

  return globalCache.getOrCompute(
    'it_search',
    { query, type, sort, maxResults, hl, gl },
    CACHE_TTL.SEARCH,
    async () => {
      let sp: string | undefined;
      if (type === 'channel') sp = SEARCH_SP.channel;
      else if (type === 'playlist') sp = SEARCH_SP.playlist;
      else if (type === 'short') sp = SEARCH_SP.short;
      else if (sort !== 'relevance' && SEARCH_SP[sort]) sp = SEARCH_SP[sort];

      const body: Record<string, unknown> = { query };
      if (sp) body.params = decodeURIComponent(sp);

      const json = await postInnerTube('search', body, { hl, gl });
      const sections =
        json?.contents?.twoColumnSearchResultsRenderer?.primaryContents?.sectionListRenderer?.contents || [];

      const videos: LeanVideo[] = [];
      const channels: LeanChannel[] = [];
      const playlists: LeanPlaylist[] = [];

      for (const sec of sections) {
        const items = sec?.itemSectionRenderer?.contents || [];
        for (const item of items) {
          if (item.videoRenderer) {
            const v = parseVideoRenderer(item.videoRenderer);
            if (v && (type !== 'short' || v.isShort)) videos.push(v);
          } else if (item.lockupViewModel) {
            const parsed = parseLockupViewModel(item.lockupViewModel);
            if (parsed?.kind === 'video') videos.push(parsed.video);
            else if (parsed?.kind === 'playlist') playlists.push(parsed.playlist);
          } else if (item.reelShelfRenderer?.items || item.gridShelfViewModel?.contents) {
            const shelfItems = item.reelShelfRenderer?.items || item.gridShelfViewModel?.contents || [];
            for (const sItem of shelfItems) {
              const sv =
                sItem.shortsLockupViewModel && parseShortsLockup(sItem.shortsLockupViewModel);
              if (sv && (type === 'short' || type === 'video')) videos.push(sv);
            }
          } else if (item.channelRenderer) {
            const ch = parseChannelRenderer(item.channelRenderer);
            if (ch) channels.push(ch);
          } else if (item.playlistRenderer) {
            const pl = parsePlaylistRenderer(item.playlistRenderer);
            if (pl) playlists.push(pl);
          }
        }
      }

      return {
        videos: videos.slice(0, maxResults),
        channels: channels.slice(0, maxResults),
        playlists: playlists.slice(0, maxResults),
      };
    }
  );
}

/**
 * Resolve any @handle, channel URL, or name into a canonical `UC...` Channel ID (0 API keys).
 */
export async function resolveChannelIdInnerTube(input: string): Promise<string> {
  const ref = parseChannelRef(input);
  if (ref.kind === 'id') return ref.value;

  return globalCache.getOrCompute(
    'it_resolve_channel',
    ref,
    7 * 24 * 60 * 60 * 1000,
    async () => {
      const targetUrl =
        ref.kind === 'handle'
          ? `https://www.youtube.com/${ref.value}`
          : ref.kind === 'url'
            ? ref.value
            : null;

      if (targetUrl) {
        try {
          const nav = await postInnerTube('navigation/resolve_url', { url: targetUrl });
          const browseId = nav?.endpoint?.browseEndpoint?.browseId;
          if (typeof browseId === 'string' && browseId.startsWith('UC')) {
            return browseId;
          }
        } catch {
          // fallback to HTML fetch
        }

        try {
          const res = await fetch(targetUrl, {
            headers: { 'User-Agent': WEB_UA },
            signal: AbortSignal.timeout(10_000),
          });
          const html = await res.text();
          const match =
            html.match(/"externalId":"(UC[a-zA-Z0-9_-]{22})"/) ||
            html.match(/"channelId":"(UC[a-zA-Z0-9_-]{22})"/);
          if (match?.[1]) return match[1];
        } catch {
          // fallback to search
        }
      }

      const searched = await searchInnerTube({ query: ref.value, type: 'channel', maxResults: 3 });
      if (searched.channels[0]?.id) return searched.channels[0].id;

      const vidSearch = await searchInnerTube({ query: ref.value, type: 'video', maxResults: 3 });
      if (vidSearch.videos[0]?.channelId) return vidSearch.videos[0].channelId;

      throw new Error(`Could not resolve YouTube channel for "${input}"`);
    }
  );
}

/**
 * Browse Channel Metadata + Videos Tab + Shorts Tab + Playlists Tab via 2026 InnerTube!
 */
export async function browseChannelInnerTube(
  channelInput: string,
  options: {
    includeVideos?: boolean;
    includeShorts?: boolean;
    includePlaylists?: boolean;
    maxResults?: number;
  } = {}
): Promise<{
  channel: LeanChannel;
  videos: LeanVideo[];
  shorts: LeanVideo[];
  playlists: LeanPlaylist[];
}> {
  const channelId = await resolveChannelIdInnerTube(channelInput);
  const maxResults = options.maxResults || 20;

  const [homeJson, videosJson, shortsJson, playlistsJson] = await Promise.all([
    globalCache.getOrCompute('it_ch_home', channelId, CACHE_TTL.CHANNEL, () =>
      postInnerTube('browse', { browseId: channelId })
    ),
    options.includeVideos
      ? globalCache.getOrCompute('it_ch_vids', channelId, CACHE_TTL.SEARCH, () =>
          postInnerTube('browse', {
            browseId: channelId,
            params: decodeURIComponent(BROWSE_TAB_PARAMS.VIDEOS),
          })
        )
      : Promise.resolve(null),
    options.includeShorts
      ? globalCache.getOrCompute('it_ch_shorts', channelId, CACHE_TTL.SEARCH, () =>
          postInnerTube('browse', {
            browseId: channelId,
            params: decodeURIComponent(BROWSE_TAB_PARAMS.SHORTS),
          })
        )
      : Promise.resolve(null),
    options.includePlaylists
      ? globalCache.getOrCompute('it_ch_pls', channelId, CACHE_TTL.CHANNEL, () =>
          postInnerTube('browse', {
            browseId: channelId,
            params: decodeURIComponent(BROWSE_TAB_PARAMS.PLAYLISTS),
          })
        )
      : Promise.resolve(null),
  ]);

  const meta = homeJson?.metadata?.channelMetadataRenderer || {};
  const pageHeader = homeJson?.header?.pageHeaderRenderer?.content?.pageHeaderViewModel;
  const c4Header = homeJson?.header?.c4TabbedHeaderRenderer;

  let subscribers: number | undefined;
  let videoCount: number | undefined;
  let handle: string | undefined;

  if (pageHeader) {
    const rows = pageHeader?.metadata?.contentMetadataViewModel?.metadataRows || [];
    for (const row of rows) {
      for (const part of row?.metadataParts || []) {
        const text = String(part?.text?.content || '');
        if (text.startsWith('@')) handle = text;
        else if (/subscriber/i.test(text)) subscribers = parseHumanCount(text);
        else if (/video/i.test(text)) videoCount = parseHumanCount(text);
      }
    }
  } else if (c4Header) {
    subscribers = parseHumanCount(extractText(c4Header.subscriberCountText));
    videoCount = parseHumanCount(extractText(c4Header.videosCountText));
    handle = extractText(c4Header.channelHandleText) || undefined;
  }

  if (!handle && typeof meta.vanityChannelUrl === 'string' && meta.vanityChannelUrl.includes('@')) {
    handle = `@${meta.vanityChannelUrl.split('@')[1]}`;
  }

  const description = meta.description || '';
  const videos = videosJson
    ? extractBrowseTabVideos(videosJson, channelId, meta.title).slice(0, maxResults)
    : [];
  const shorts = shortsJson
    ? extractBrowseTabShorts(shortsJson, channelId, meta.title).slice(0, maxResults)
    : [];
  const playlists = playlistsJson ? extractBrowseTabPlaylists(playlistsJson).slice(0, maxResults) : [];

  const latestUploadAt = videos[0]?.publishedAt || shorts[0]?.publishedAt;

  const channel: LeanChannel = {
    id: channelId,
    title: meta.title || pageHeader?.title?.dynamicTextViewModel?.text?.content || channelId,
    handle,
    url: handle ? `https://www.youtube.com/${handle}` : `https://www.youtube.com/channel/${channelId}`,
    description: description || undefined,
    subscribers,
    videoCount,
    uploadsPlaylistId: channelId.startsWith('UC') ? `UU${channelId.slice(2)}` : undefined,
    latestUploadAt,
    avatarUrl: meta.avatar?.thumbnails?.[0]?.url || undefined,
    source: 'innertube',
  };

  return { channel, videos, shorts, playlists };
}

/**
 * Ultra-fast (~50ms) YouTube Channel Atom RSS Feed parser (0 API keys, exact publish timestamps!).
 */
export async function fetchChannelRss(channelInput: string): Promise<LeanVideo[]> {
  const channelId = await resolveChannelIdInnerTube(channelInput);
  return globalCache.getOrCompute('yt_rss', channelId, 15 * 60 * 1000, async () => {
    const res = await fetch(`https://www.youtube.com/feeds/videos.xml?channel_id=${channelId}`, {
      headers: { 'User-Agent': WEB_UA },
      signal: AbortSignal.timeout(8_000),
    });
    if (!res.ok) return [];
    const xml = await res.text();
    const channelTitle = decodeHtmlEntities(xml.match(/<author>\s*<name>([^<]+)<\/name>/)?.[1] || '');
    const entries = [...xml.matchAll(/<entry>([\s\S]*?)<\/entry>/g)].map((m) => m[1]);

    return entries.map((entry) => {
      const id = entry.match(/<yt:videoId>([^<]+)<\/yt:videoId>/)?.[1] || '';
      const title = decodeHtmlEntities(entry.match(/<title>([^<]+)<\/title>/)?.[1] || '');
      const publishedAt = entry.match(/<published>([^<]+)<\/published>/)?.[1];
      const viewsStr = entry.match(/<media:statistics views="(\d+)"/)?.[1];
      const likesStr = entry.match(/<media:starRating count="(\d+)"/)?.[1];
      const desc = decodeHtmlEntities(entry.match(/<media:description>([\s\S]*?)<\/media:description>/)?.[1] || '');
      const linkHref = entry.match(/<link rel="alternate" href="([^"]+)"/)?.[1] || '';
      const views = viewsStr ? Number(viewsStr) : undefined;
      const likes = likesStr ? Number(likesStr) : undefined;
      const isShort = linkHref.includes('/shorts/');

      return {
        id,
        url: linkHref || `https://www.youtube.com/watch?v=${id}`,
        title,
        channelId,
        channelTitle: channelTitle || undefined,
        publishedAt,
        isShort,
        views,
        likes,
        viewsPerDay: calcViewsPerDay(views, publishedAt),
        description: desc ? desc.slice(0, 300) : undefined,
        source: 'rss' as const,
      };
    });
  });
}

/**
 * Fetch Video Comments via 2026 InnerTube (supports `commentEntityPayload` + `commentThreadRenderer`, 0 API keys!).
 */
export async function fetchCommentsInnerTube(
  videoInput: string,
  maxResults = 30,
  sortBy: 'top' | 'newest' = 'top'
): Promise<LeanComment[]> {
  const videoId = extractVideoId(videoInput);

  return globalCache.getOrCompute(
    'it_comments',
    { videoId, maxResults, sortBy },
    CACHE_TTL.COMMENTS,
    async () => {
      const nextJson = await postInnerTube('next', { videoId });
      const nextStr = JSON.stringify(nextJson);
      const tokens = [...nextStr.matchAll(/"continuationCommand":\{"token":"([^"]+)"/g)].map((m) => m[1]);
      if (tokens.length === 0) return [];

      // Locate comment section continuation
      let commentBatchJson: any = null;
      for (const tok of tokens.slice(0, 4)) {
        const candidate = await postInnerTube('next', { continuation: tok }).catch(() => null);
        if (!candidate) continue;
        const cStr = JSON.stringify(candidate);
        if (cStr.includes('commentEntityPayload') || cStr.includes('commentThreadRenderer') || cStr.includes('sortFilterSubMenuRenderer')) {
          // Check if sortBy === 'newest' has a dedicated sort menu token
          if (sortBy === 'newest') {
            const sortTokens = [
              ...cStr.matchAll(/"title":"Newest first"[^}]*"token":"([^"]+)"/g),
              ...cStr.matchAll(/"serviceEndpoint":\{"clickTrackingParams":"[^"]+","commandMetadata":\{[^}]+\},"continuationCommand":\{"token":"([^"]+)"/g),
            ].map((m) => m[1]);
            const newestToken = sortTokens[1] || sortTokens[0];
            if (newestToken) {
              const sorted = await postInnerTube('next', { continuation: newestToken }).catch(() => null);
              if (sorted) {
                commentBatchJson = sorted;
                break;
              }
            }
          }
          commentBatchJson = candidate;
          break;
        }
      }

      if (!commentBatchJson) return [];

      const comments: LeanComment[] = [];
      let currentJson = commentBatchJson;
      let pages = 0;

      while (currentJson && comments.length < maxResults && pages < 3) {
        pages++;
        const parsed = extractCommentsFromPayload(currentJson);
        for (const c of parsed) {
          if (!comments.some((existing) => existing.id === c.id)) {
            comments.push(c);
          }
          if (comments.length >= maxResults) break;
        }

        if (comments.length >= maxResults) break;
        // Find next page continuation token inside appendContinuationItemsAction
        const nextTok = findNextContinuationToken(currentJson);
        if (!nextTok) break;
        currentJson = await postInnerTube('next', { continuation: nextTok }).catch(() => null);
      }

      return comments.slice(0, maxResults);
    }
  );
}

/**
 * Fetch Playlist Details + Items via InnerTube (0 API keys).
 */
export async function fetchPlaylistInnerTube(
  playlistInput: string,
  maxResults = 50
): Promise<LeanPlaylist> {
  const playlistId = extractPlaylistId(playlistInput);
  return globalCache.getOrCompute('it_playlist', { playlistId, maxResults }, CACHE_TTL.VIDEO, async () => {
    const browseId = playlistId.startsWith('VL') ? playlistId : `VL${playlistId}`;
    const json = await postInnerTube('browse', { browseId });

    const header =
      json?.header?.playlistHeaderRenderer ||
      json?.header?.pageHeaderRenderer?.content?.pageHeaderViewModel;
    const title =
      extractText(header?.title) ||
      header?.title?.dynamicTextViewModel?.text?.content ||
      json?.metadata?.playlistMetadataRenderer?.title ||
      playlistId;
    const description =
      extractText(header?.descriptionText) ||
      json?.metadata?.playlistMetadataRenderer?.description ||
      undefined;
    const channelTitle = extractText(header?.ownerText) || undefined;

    const items: LeanVideo[] = [];
    const tabs = json?.contents?.twoColumnBrowseResultsRenderer?.tabs || [];
    const contents =
      tabs[0]?.tabRenderer?.content?.sectionListRenderer?.contents?.[0]?.itemSectionRenderer?.contents?.[0]
        ?.playlistVideoListRenderer?.contents || [];

    for (const entry of contents) {
      const pvr = entry?.playlistVideoRenderer;
      if (pvr?.videoId) {
        const durationSec = parseDurationSeconds(pvr.lengthSeconds || extractText(pvr.lengthText));
        items.push({
          id: pvr.videoId,
          url: `https://www.youtube.com/watch?v=${pvr.videoId}`,
          title: extractText(pvr.title) || pvr.videoId,
          channelId: pvr.shortBylineText?.runs?.[0]?.navigationEndpoint?.browseEndpoint?.browseId,
          channelTitle: extractText(pvr.shortBylineText) || undefined,
          durationSec,
          duration: durationSec !== undefined ? formatTimestamp(durationSec) : undefined,
          views: parseHumanCount(extractText(pvr.videoInfo)),
          source: 'innertube',
        });
      }
      if (items.length >= maxResults) break;
    }

    return {
      id: playlistId,
      url: `https://www.youtube.com/playlist?list=${playlistId}`,
      title,
      channelTitle,
      description,
      itemCount: items.length,
      items,
    };
  });
}

