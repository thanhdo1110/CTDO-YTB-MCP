function extractText(node: any): string {
  if (!node) return '';
  if (typeof node === 'string') return node;
  if (typeof node.simpleText === 'string') return node.simpleText;
  if (typeof node.content === 'string') return node.content;
  if (Array.isArray(node.runs)) {
    return node.runs.map((r: any) => r?.text || '').join('');
  }
  return '';
}

function parseVideoRenderer(vr: any): LeanVideo | null {
  const id = vr?.videoId;
  if (!id) return null;
  const title = extractText(vr.title);
  const durationText =
    extractText(vr.lengthText) ||
    vr.thumbnailOverlays?.find((o: any) => o.thumbnailOverlayTimeStatusRenderer)?.thumbnailOverlayTimeStatusRenderer
      ?.text?.simpleText;
  const durationSec = parseDurationSeconds(durationText);
  const views = parseHumanCount(extractText(vr.viewCountText) || extractText(vr.shortViewCountText));
  const publishedText = extractText(vr.publishedTimeText) || undefined;
  const publishedAt = parseRelativeDate(publishedText);
  const ownerRun = (vr.ownerText?.runs || vr.longBylineText?.runs || [])[0];
  let channelId: string | undefined =
    ownerRun?.navigationEndpoint?.browseEndpoint?.browseId ||
    vr.channelThumbnailSupportedRenderers?.channelThumbnailWithLinkRenderer?.navigationEndpoint?.browseEndpoint
      ?.browseId;
  if (!channelId) {
    const vrStr = JSON.stringify(vr.ownerText || vr.channelThumbnailSupportedRenderers || {});
    channelId = vrStr.match(/"browseId":"(UC[a-zA-Z0-9_-]{22})"/)?.[1];
  }
  const canonicalUrl = ownerRun?.navigationEndpoint?.commandMetadata?.webCommandMetadata?.url || '';
  const channelHandle = canonicalUrl.startsWith('/@') ? canonicalUrl.slice(1) : undefined;
  const navUrl = vr.navigationEndpoint?.commandMetadata?.webCommandMetadata?.url || '';
  const isShort = navUrl.includes('/shorts/') || durationText?.toUpperCase() === 'SHORTS';

  return {
    id,
    url: isShort ? `https://www.youtube.com/shorts/${id}` : `https://www.youtube.com/watch?v=${id}`,
    title,
    channelId,
    channelTitle: ownerRun?.text || undefined,
    channelHandle,
    publishedAt,
    publishedText,
    durationSec,
    duration: durationSec !== undefined ? formatTimestamp(durationSec) : undefined,
    isShort,
    isLive: Boolean(vr.badges?.some((b: any) => /live/i.test(b?.metadataBadgeRenderer?.label || ''))),
    views,
    viewsPerDay: calcViewsPerDay(views, publishedAt),
    description: extractText(vr.detailedMetadataSnippets?.[0]?.snippetText) || undefined,
    source: 'innertube',
  };
}

function parseLockupViewModel(
  lvm: any,
  fallbackChannelId?: string,
  fallbackChannelTitle?: string
): { kind: 'video'; video: LeanVideo } | { kind: 'playlist'; playlist: LeanPlaylist } | null {
  const id = lvm?.contentId;
  if (!id) return null;
  const contentType = String(lvm.contentType || '');
  const title = lvm?.metadata?.lockupMetadataViewModel?.title?.content || id;
  const rows =
    lvm?.metadata?.lockupMetadataViewModel?.metadata?.contentMetadataViewModel?.metadataRows || [];

  if (contentType.includes('PLAYLIST')) {
    return {
      kind: 'playlist',
      playlist: {
        id,
        url: `https://www.youtube.com/playlist?list=${id}`,
        title,
        channelId: fallbackChannelId,
        channelTitle: fallbackChannelTitle,
      },
    };
  }

  let views: number | undefined;
  let publishedText: string | undefined;
  let channelTitle = fallbackChannelTitle;

  for (const row of rows) {
    for (const part of row?.metadataParts || []) {
      const text = String(part?.text?.content || '');
      if (/view/i.test(text)) views = parseHumanCount(text);
      else if (/ago|streamed|premiered/i.test(text)) publishedText = text;
      else if (!channelTitle && text) channelTitle = text;
    }
  }

  const overlays = lvm?.contentImage?.thumbnailViewModel?.overlays || [];
  let durationText: string | undefined;
  for (const ov of overlays) {
    const badge = ov?.thumbnailBottomOverlayViewModel?.badges?.[0]?.thumbnailBadgeViewModel?.text;
    if (badge) {
      durationText = badge;
      break;
    }
  }

  const durationSec = parseDurationSeconds(durationText);
  const publishedAt = parseRelativeDate(publishedText);
  const isShort = durationSec !== undefined && durationSec <= 60 && durationText?.toUpperCase() === 'SHORTS';

  return {
    kind: 'video',
    video: {
      id,
      url: `https://www.youtube.com/watch?v=${id}`,
      title,
      channelId: fallbackChannelId,
      channelTitle,
      publishedAt,
      publishedText,
      durationSec,
      duration: durationSec !== undefined ? formatTimestamp(durationSec) : durationText,
      isShort,
      views,
      viewsPerDay: calcViewsPerDay(views, publishedAt),
      source: 'innertube',
    },
  };
}

function parseShortsLockup(
  slm: any,
  channelId?: string,
  channelTitle?: string
): LeanVideo | null {
  const tapUrl = slm?.onTap?.innertubeCommand?.commandMetadata?.webCommandMetadata?.url || '';
  const idMatch = tapUrl.match(/\/shorts\/([a-zA-Z0-9_-]{11})/) || String(slm?.entityId || '').match(/([a-zA-Z0-9_-]{11})$/);
  const id = idMatch?.[1];
  if (!id) return null;

  const title = slm?.overlayMetadata?.primaryText?.content || slm?.accessibilityText?.split(',')[0] || id;
  const viewsText = slm?.overlayMetadata?.secondaryText?.content || '';
  const views = parseHumanCount(viewsText);

  return {
    id,
    url: `https://www.youtube.com/shorts/${id}`,
    title,
    channelId,
    channelTitle,
    isShort: true,
    durationSec: 45,
    duration: '0:45',
    views,
    source: 'innertube',
  };
}

function parseChannelRenderer(cr: any): LeanChannel | null {
  const id = cr?.channelId;
  if (!id) return null;
  const title = extractText(cr.title);
  // Note: YouTube sometimes swaps subscriberCountText and videoCountText when @handle is shown!
  const t1 = extractText(cr.subscriberCountText);
  const t2 = extractText(cr.videoCountText);
  let handle: string | undefined;
  let subscribers: number | undefined;
  let videoCount: number | undefined;

  for (const t of [t1, t2]) {
    if (t.startsWith('@')) handle = t;
    else if (/subscriber/i.test(t)) subscribers = parseHumanCount(t);
    else if (/video/i.test(t)) videoCount = parseHumanCount(t);
  }
  const navUrl = cr.navigationEndpoint?.browseEndpoint?.canonicalBaseUrl || '';
  if (!handle && navUrl.startsWith('/@')) handle = navUrl.slice(1);

  return {
    id,
    title,
    handle,
    url: handle ? `https://www.youtube.com/${handle}` : `https://www.youtube.com/channel/${id}`,
    description: extractText(cr.descriptionSnippet) || undefined,
    subscribers,
    videoCount,
    source: 'innertube',
  };
}

function parsePlaylistRenderer(pr: any): LeanPlaylist | null {
  const id = pr?.playlistId;
  if (!id) return null;
  return {
    id,
    url: `https://www.youtube.com/playlist?list=${id}`,
    title: extractText(pr.title) || id,
    channelId: pr.shortBylineText?.runs?.[0]?.navigationEndpoint?.browseEndpoint?.browseId,
    channelTitle: extractText(pr.shortBylineText) || undefined,
    itemCount: parseHumanCount(pr.videoCount || extractText(pr.videoCountText)),
  };
}

function extractBrowseTabVideos(json: any, channelId: string, channelTitle?: string): LeanVideo[] {
  const tabs = json?.contents?.twoColumnBrowseResultsRenderer?.tabs || [];
  const selected = tabs.find((t: any) => t?.tabRenderer?.selected) || tabs[1] || tabs[0];
  const contents = selected?.tabRenderer?.content?.richGridRenderer?.contents || [];
  const out: LeanVideo[] = [];

  for (const entry of contents) {
    const c = entry?.richItemRenderer?.content;
    if (!c) continue;
    if (c.lockupViewModel) {
      const parsed = parseLockupViewModel(c.lockupViewModel, channelId, channelTitle);
      if (parsed?.kind === 'video') out.push(parsed.video);
    } else if (c.videoRenderer) {
      const v = parseVideoRenderer(c.videoRenderer);
      if (v) {
        v.channelId = v.channelId || channelId;
        v.channelTitle = v.channelTitle || channelTitle;
        out.push(v);
      }
    }
  }
  return out;
}

function extractBrowseTabShorts(json: any, channelId: string, channelTitle?: string): LeanVideo[] {
  const tabs = json?.contents?.twoColumnBrowseResultsRenderer?.tabs || [];
  const selected = tabs.find((t: any) => t?.tabRenderer?.selected) || tabs[2] || tabs[0];
  const contents = selected?.tabRenderer?.content?.richGridRenderer?.contents || [];
  const out: LeanVideo[] = [];

  for (const entry of contents) {
    const slm = entry?.richItemRenderer?.content?.shortsLockupViewModel;
    if (slm) {
      const s = parseShortsLockup(slm, channelId, channelTitle);
      if (s) out.push(s);
    }
  }
  return out;
}

function extractBrowseTabPlaylists(json: any): LeanPlaylist[] {
  const tabs = json?.contents?.twoColumnBrowseResultsRenderer?.tabs || [];
  const selected = tabs.find((t: any) => t?.tabRenderer?.selected) || tabs[0];
  const contents =
    selected?.tabRenderer?.content?.sectionListRenderer?.contents?.[0]?.itemSectionRenderer?.contents?.[0]
      ?.gridRenderer?.items ||
    selected?.tabRenderer?.content?.richGridRenderer?.contents ||
    [];
  const out: LeanPlaylist[] = [];

  for (const item of contents) {
    const lvm = item?.richItemRenderer?.content?.lockupViewModel || item?.lockupViewModel;
    if (lvm) {
      const parsed = parseLockupViewModel(lvm);
      if (parsed?.kind === 'playlist') out.push(parsed.playlist);
    } else if (item?.gridPlaylistRenderer) {
      const g = item.gridPlaylistRenderer;
      if (g.playlistId) {
        out.push({
          id: g.playlistId,
          url: `https://www.youtube.com/playlist?list=${g.playlistId}`,
          title: extractText(g.title) || g.playlistId,
          itemCount: parseHumanCount(extractText(g.videoCountText)),
        });
      }
    }
  }
  return out;
}

function parseChaptersFromNext(nextJson: any): Chapter[] {
  const chapters: Chapter[] = [];
  try {
    const panels = nextJson?.engagementPanels || [];
    for (const panel of panels) {
      const contents =
        panel?.engagementPanelSectionListRenderer?.content?.macroMarkersListRenderer?.contents || [];
      for (const item of contents) {
        const m = item?.macroMarkersListItemRenderer;
        if (!m) continue;
        const title = extractText(m.title);
        const timeStr = extractText(m.timeDescription);
        const startSec = parseDurationSeconds(timeStr);
        if (title && startSec !== undefined) {
          chapters.push({ title, startSec, timestamp: formatTimestamp(startSec) });
        }
      }
    }
  } catch {
    // ignore
  }
  return chapters;
}

function parseRelatedFromNext(nextJson: any): LeanVideo[] {
  const out: LeanVideo[] = [];
  const results = nextJson?.contents?.twoColumnWatchNextResults?.secondaryResults?.secondaryResults?.results || [];
  for (const item of results) {
    if (item.compactVideoRenderer) {
      const cv = item.compactVideoRenderer;
      if (!cv.videoId) continue;
      const durationSec = parseDurationSeconds(extractText(cv.lengthText));
      const views = parseHumanCount(extractText(cv.viewCountText));
      const publishedText = extractText(cv.publishedTimeText) || undefined;
      const publishedAt = parseRelativeDate(publishedText);
      out.push({
        id: cv.videoId,
        url: `https://www.youtube.com/watch?v=${cv.videoId}`,
        title: extractText(cv.title),
        channelId: cv.longBylineText?.runs?.[0]?.navigationEndpoint?.browseEndpoint?.browseId,
        channelTitle: extractText(cv.longBylineText) || undefined,
        publishedAt,
        publishedText,
        durationSec,
        duration: durationSec !== undefined ? formatTimestamp(durationSec) : undefined,
        views,
        viewsPerDay: calcViewsPerDay(views, publishedAt),
        source: 'innertube',
      });
    } else if (item.lockupViewModel) {
      const parsed = parseLockupViewModel(item.lockupViewModel);
      if (parsed?.kind === 'video') out.push(parsed.video);
    }
    if (out.length >= 20) break;
  }
  return out;
}

function extractCommentsFromPayload(json: any): LeanComment[] {
  const out: LeanComment[] = [];

  // 1. Modern 2025/2026 entityBatchUpdate mutations (`commentEntityPayload`)
  const mutations = json?.frameworkUpdates?.entityBatchUpdate?.mutations || [];
  for (const mut of mutations) {
    const p = mut?.payload?.commentEntityPayload;
    if (!p?.properties?.commentId) continue;
    const props = p.properties;
    const author = p.author || {};
    const toolbar = p.toolbar || {};
    const publishedText = props.publishedTime || undefined;
    out.push({
      id: String(props.commentId),
      author: String(author.displayName || author.channelCommand?.innertubeCommand?.browseEndpoint?.canonicalBaseUrl || 'User'),
      authorChannelId: author.channelId || undefined,
      text: String(props.content?.content || '').trim(),
      likes: parseHumanCount(toolbar.likeCountNotliked || toolbar.likeCountLiked) || 0,
      replyCount: parseHumanCount(toolbar.replyCount) || 0,
      publishedText,
      publishedAt: parseRelativeDate(publishedText),
      isHearted: Boolean(toolbar.heartActiveTooltip),
    });
  }

  if (out.length > 0) return out;

  // 2. Legacy fallback: commentThreadRenderer
  const actions = json?.onResponseReceivedEndpoints || [];
  for (const act of actions) {
    const items =
      act?.reloadContinuationItemsCommand?.continuationItems ||
      act?.appendContinuationItemsAction?.continuationItems ||
      [];
    for (const item of items) {
      const c = item?.commentThreadRenderer?.comment?.commentRenderer;
      if (!c?.commentId) continue;
      const publishedText = extractText(c.publishedTimeText) || undefined;
      out.push({
        id: String(c.commentId),
        author: extractText(c.authorText) || 'User',
        authorChannelId: c.authorEndpoint?.browseEndpoint?.browseId,
        text: extractText(c.contentText).trim(),
        likes: parseHumanCount(extractText(c.voteCount)) || 0,
        replyCount: Number(item?.commentThreadRenderer?.commentRepliesRenderer?.moreText?.runs?.[0]?.text) || 0,
        publishedText,
        publishedAt: parseRelativeDate(publishedText),
        isPinned: Boolean(c.pinnedCommentBadge),
      });
    }
  }
  return out;
}

function findNextContinuationToken(json: any): string | null {
  const actions = json?.onResponseReceivedEndpoints || [];
  for (const act of actions) {
    const items =
      act?.appendContinuationItemsAction?.continuationItems ||
      act?.reloadContinuationItemsCommand?.continuationItems ||
      [];
    for (let i = items.length - 1; i >= 0; i--) {
      const tok = items[i]?.continuationItemRenderer?.continuationEndpoint?.continuationCommand?.token;
      if (tok) return tok;
    }
  }
  return null;
}
