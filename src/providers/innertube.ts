async function postInnerTube(
  endpoint: string,
  body: Record<string, unknown>,
  options: { client?: Record<string, unknown>; ua?: string; hl?: string; gl?: string; timeoutMs?: number } = {}
): Promise<any> {
  const hl = options.hl || process.env.CTDO_DEFAULT_LANG || 'en';
  const gl = options.gl || process.env.CTDO_DEFAULT_REGION || 'US';
  const client = { ...(options.client || WEB_CLIENT), hl, gl };
  const ua = options.ua || WEB_UA;

  const res = await fetch(`https://www.youtube.com/youtubei/v1/${endpoint}?prettyPrint=false`, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'User-Agent': ua,
      'Accept-Language': `${hl},en;q=0.8`,
    },
    body: JSON.stringify({
      context: { client },
      ...body,
    }),
    signal: AbortSignal.timeout(options.timeoutMs || 12_000),
  });

  if (!res.ok) {
    throw new Error(`InnerTube ${endpoint} HTTP ${res.status}`);
  }
  return res.json();
}

